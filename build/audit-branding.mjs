#!/usr/bin/env node
// Lists user-visible upstream branding left in a prepared Code - OSS checkout:
// "VS Code", "Visual Studio Code", "Microsoft", and links to Microsoft's sites,
// in UI strings (localize/nls), built-in extension manifests and product.json.
// Comments, copyright headers and tests are skipped. Writes Markdown.
//
//   node build/audit-branding.mjs [--out docs/branding-audit.md]
import * as fs from "node:fs";
import * as path from "node:path";
import { ROOT, VSCODE, readJson } from "./lib.mjs";

const outIdx = process.argv.indexOf("--out");
const outFile = outIdx > 0 ? path.resolve(process.argv[outIdx + 1]) : undefined;

const NAME = /\bVS ?Code\b|Visual Studio Code|\bMicrosoft\b/;
const LINK = /https?:\/\/(?:code\.visualstudio\.com|aka\.ms|go\.microsoft\.com|learn\.microsoft\.com|marketplace\.visualstudio\.com)[^\s'"`)]*/;

const findings = { ui: [], uiLinks: [], extensions: [], product: [] };

function walk(dir, filter, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (["node_modules", "test", "tests", "fixtures", ".build", "out", "out-build"].includes(e.name)) continue;
      walk(p, filter, out);
    } else if (filter(p)) out.push(p);
  }
  return out;
}

const rel = (p) => path.relative(VSCODE, p).split(path.sep).join("/");

// 1. UI strings in the workbench and platform code: localize(...) / localize2(...) message arguments.
const LOCALIZE = /\blocalize2?\(\s*(?:'[^']*'|"[^"]*"|\{[^}]*\})\s*,\s*(['"`])((?:\\.|(?!\1).)*)\1/g;
for (const file of walk(path.join(VSCODE, "src"), (p) => p.endsWith(".ts") && !p.endsWith(".test.ts") && !p.includes(`${path.sep}test${path.sep}`))) {
  const lines = fs.readFileSync(file, "utf8").split("\n");
  lines.forEach((line, i) => {
    const t = line.trim();
    if (t.startsWith("//") || t.startsWith("*") || t.startsWith("/*")) return;
    for (const m of line.matchAll(LOCALIZE)) {
      const msg = m[2];
      if (NAME.test(msg)) findings.ui.push({ where: `${rel(file)}:${i + 1}`, text: msg });
      else if (LINK.test(msg)) findings.uiLinks.push({ where: `${rel(file)}:${i + 1}`, text: msg });
    }
    // Links used as strings outside localize (help buttons, "learn more").
    if (!LOCALIZE.test(line)) {
      const link = LINK.exec(line);
      if (link && /['"`]/.test(line)) findings.uiLinks.push({ where: `${rel(file)}:${i + 1}`, text: link[0] });
    }
    LOCALIZE.lastIndex = 0;
  });
}

// 2. Built-in extensions: display names and descriptions users see in the Extensions view.
for (const ext of fs.readdirSync(path.join(VSCODE, "extensions"), { withFileTypes: true })) {
  if (!ext.isDirectory() || ext.name === "synapse-collab") continue;
  for (const f of ["package.nls.json", "package.json"]) {
    const file = path.join(VSCODE, "extensions", ext.name, f);
    if (!fs.existsSync(file)) continue;
    let data;
    try {
      data = readJson(file);
    } catch {
      continue;
    }
    const strings = f === "package.json" ? { displayName: data.displayName, description: data.description } : data;
    for (const [k, v] of Object.entries(strings)) {
      const text = typeof v === "string" ? v : typeof v?.message === "string" ? v.message : undefined;
      if (text && (NAME.test(text) || LINK.test(text))) findings.extensions.push({ where: `extensions/${ext.name}/${f}#${k}`, text });
    }
  }
}

// 3. product.json after Synapse's overrides.
const product = readJson(path.join(VSCODE, "product.json"));
(function scan(obj, prefix) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (typeof v === "string" && (NAME.test(v) || LINK.test(v))) findings.product.push({ where: `product.json#${key}`, text: v });
    else if (v && typeof v === "object") scan(v, key);
  }
})(product, "");

// Report
const clip = (s) => (s.length > 140 ? s.slice(0, 137) + "…" : s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const section = (title, list, note) =>
  [
    `## ${title} (${list.length})`,
    "",
    note,
    "",
    ...(list.length ? ["| Where | Text |", "| --- | --- |", ...list.slice(0, 40).map((f) => `| \`${f.where}\` | ${clip(f.text)} |`)] : ["None."]),
    list.length > 40 ? `\n…and ${list.length - 40} more (run \`node build/audit-branding.mjs\` for the full list).` : "",
    "",
  ].join("\n");

const upstream = readJson(path.join(ROOT, "build", "upstream.json"));
const md = [
  "# Branding audit",
  "",
  `Upstream branding still visible to users in a prepared Code - OSS ${upstream.tag} checkout (patches applied, \`product.json\` merged). Generated by \`node build/audit-branding.mjs\`; comments, copyright headers and tests are excluded.`,
  "",
  "| Area | Count |",
  "| --- | --- |",
  `| UI strings naming VS Code or Microsoft | ${findings.ui.length} |`,
  `| Links to Microsoft sites in the UI | ${findings.uiLinks.length} |`,
  `| Built-in extension names and descriptions | ${findings.extensions.length} |`,
  `| product.json values | ${findings.product.length} |`,
  "",
  section("UI strings naming VS Code or Microsoft", findings.ui, "Translatable messages that mention the product or company by name, rather than through `product.nameLong`."),
  section("Links to Microsoft sites", findings.uiLinks, "Documentation and help links. Functional, but they send Synapse users to VS Code's documentation."),
  section("Built-in extensions", findings.extensions, "Text in the Extensions view for extensions that ship with Code - OSS."),
  section("product.json", findings.product, "Values left from upstream's product.json after Synapse's overrides."),
].join("\n");

if (outFile) {
  fs.writeFileSync(outFile, md.trimEnd() + "\n");
  console.log(`wrote ${path.relative(process.cwd(), outFile)}`);
}
console.log(`ui: ${findings.ui.length}, links: ${findings.uiLinks.length}, extensions: ${findings.extensions.length}, product.json: ${findings.product.length}`);
